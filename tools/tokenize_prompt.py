#!/usr/bin/env python3
"""Tokenizes a prompt for the ESP32 and detokenizes what it prints (requires `pip install tokenizers`).

  # prompt -> ids (optionally also the include file used by main.cpp)
  python tools/tokenize_prompt.py ethoric_original "The lighthouse stood" --write-inc main/prompt.inc

  # ids -> text
  python tools/tokenize_prompt.py ethoric_original --decode "461,307,412"

  # serial monitor log (lines "TOKEN n") -> text. Use "-" to read from standard input.
  python tools/tokenize_prompt.py ethoric_original --decode-log monitor.log
"""
import argparse
import os
import re
import sys


def parse_log_ids(lines):
    """Extracts ids from 'TOKEN n' lines (ignores other log output, including the IDF log prefix)."""
    ids = []
    for line in lines:
        m = re.search(r"(?:^|\s)TOKEN (\d+)\s*$", line)
        if m:
            ids.append(int(m.group(1)))
    return ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir", help="directory containing tokenizer.json")
    ap.add_argument("prompt", nargs="?", help="prompt text")
    ap.add_argument("--write-inc", help="write main.cpp's prompt.inc to this path")
    ap.add_argument("--decode", help="comma-separated ids -> text")
    ap.add_argument("--decode-log", help="log file (or -) with 'TOKEN n' lines -> text")
    a = ap.parse_args()

    from tokenizers import Tokenizer
    tok = Tokenizer.from_file(os.path.join(a.dir, "tokenizer.json"))

    if a.decode is not None:
        print(tok.decode([int(t) for t in a.decode.split(",") if t.strip()]))
    elif a.decode_log is not None:
        src = sys.stdin if a.decode_log == "-" else open(a.decode_log, encoding="utf-8", errors="replace")
        ids = parse_log_ids(src)
        print(f"{len(ids)} tokens", file=sys.stderr)
        print(tok.decode(ids))
    elif a.prompt is not None:
        ids = tok.encode(a.prompt).ids
        print(",".join(map(str, ids)))
        print(f"{len(ids)} tokens", file=sys.stderr)
        if a.write_inc:
            with open(a.write_inc, "w", encoding="utf-8") as f:
                f.write(f"// Generated by tools/tokenize_prompt.py. Prompt: {a.prompt!r}\n")
                f.write(f"static const int PROMPT[] = {{{', '.join(map(str, ids))}}};\n")
            print(f"wrote {a.write_inc}", file=sys.stderr)
    else:
        ap.error("provide a prompt, --decode or --decode-log")


if __name__ == "__main__":
    main()
